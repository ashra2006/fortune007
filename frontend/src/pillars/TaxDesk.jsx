import { useMemo, useRef, useState } from "react";
import { toast } from "sonner";
import { Upload, FileDown, Plus, Trash2, Save } from "lucide-react";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { api, errMsg } from "@/lib/api";
import GstReturns from "@/pillars/GstReturns";

const RATES = [0, 5, 12, 18, 28];
const field = "w-full bg-slate-950/70 border border-slate-800 rounded-lg px-3 py-2 text-sm outline-none focus:border-orange-500/60";
const money = (n) => Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const newLine = () => ({ description: "", hsn: "", quantity: 1, unit_price: 0, gst_rate: 18 });

export const computeLine = (l, inclusive, inter) => {
  const gross = Number(l.quantity || 0) * Number(l.unit_price || 0);
  const r = Number(l.gst_rate || 0);
  const taxable = inclusive ? gross / (1 + r / 100) : gross;
  const tax = taxable * (r / 100);
  return { taxable, cgst: inter ? 0 : tax / 2, sgst: inter ? 0 : tax / 2, igst: inter ? tax : 0, total: taxable + tax };
};

const thisMonth = () => new Date().toISOString().slice(0, 7);
const periodFromDate = (s) => {
  const m = (s || "").match(/(\d{4})[-/.](\d{1,2})[-/.]\d{1,2}/) || (s || "").match(/\d{1,2}[-/.](\d{1,2})[-/.](\d{4})/);
  if (!m) return null;
  const [y, mo] = m[1].length === 4 ? [m[1], m[2]] : [m[2], m[1]];
  return Number(mo) >= 1 && Number(mo) <= 12 ? `${y}-${String(mo).padStart(2, "0")}` : null;
};

function Calculator({ ask }) {
  const [meta, setMeta] = useState({ vendor_name: "", vendor_gstin: "", buyer_name: "", buyer_gstin: "", invoice_number: "", invoice_date: "" });
  const [lines, setLines] = useState([newLine()]);
  const [inclusive, setInclusive] = useState(false);
  const [inter, setInter] = useState(false);
  const [busy, setBusy] = useState(false);
  const [kind, setKind] = useState("sales");
  const [period, setPeriod] = useState(thisMonth());
  const fileRef = useRef(null);

  const saveInvoice = async () => {
    try {
      await api.post("/gst/invoices", { kind, period, inter, inclusive, meta, lines: lines.map((l) => ({ ...l, quantity: Number(l.quantity) || 0, unit_price: Number(l.unit_price) || 0, gst_rate: Number(l.gst_rate) || 0 })) });
      toast.success(`Saved as ${kind} invoice for ${period}`);
    } catch (e) { toast.error(errMsg(e)); }
  };

  const rows = useMemo(() => lines.map((l) => ({ ...l, ...computeLine(l, inclusive, inter) })), [lines, inclusive, inter]);
  const tot = rows.reduce((a, r) => ({ taxable: a.taxable + r.taxable, cgst: a.cgst + r.cgst, sgst: a.sgst + r.sgst, igst: a.igst + r.igst, total: a.total + r.total }), { taxable: 0, cgst: 0, sgst: 0, igst: 0, total: 0 });

  const upd = (i, k, v) => setLines(lines.map((l, j) => (j === i ? { ...l, [k]: v } : l)));

  const extract = async (file) => {
    if (!file) return;
    setBusy(true);
    const fd = new FormData();
    fd.append("file", file);
    try {
      const { data } = await api.post("/gst/extract", fd);
      const d = data.data;
      setMeta({ vendor_name: d.vendor_name || "", vendor_gstin: d.vendor_gstin || "", buyer_name: d.buyer_name || "", buyer_gstin: d.buyer_gstin || "", invoice_number: d.invoice_number || "", invoice_date: d.invoice_date || "" });
      setInter(d.supply_type === "inter" || (Number(d.igst) > 0 && !Number(d.cgst)));
      setInclusive(false);
      const p = periodFromDate(d.invoice_date);
      if (p) setPeriod(p);
      if (d.line_items?.length) setLines(d.line_items.map((l) => ({ description: l.description || "", hsn: l.hsn || "", quantity: parseFloat(l.quantity) || 1, unit_price: parseFloat(l.unit_price) || 0, gst_rate: parseFloat(l.gst_rate) || 0 })));
      toast.success(`Extracted ${d.line_items?.length || 0} line items`);
    } catch (e) { toast.error(errMsg(e)); }
    setBusy(false);
    fileRef.current.value = "";
  };

  const pdf = () => {
    const doc = new jsPDF();
    doc.setFontSize(18); doc.text("GST Tax Computation", 14, 18);
    doc.setFontSize(9); doc.setTextColor(110);
    doc.text(`Generated by Fortune 007 · ${new Date().toLocaleString("en-IN")}`, 14, 24);
    doc.setTextColor(20); doc.setFontSize(10);
    const m = [["Vendor", `${meta.vendor_name} ${meta.vendor_gstin ? "(" + meta.vendor_gstin + ")" : ""}`], ["Buyer", `${meta.buyer_name} ${meta.buyer_gstin ? "(" + meta.buyer_gstin + ")" : ""}`],
      ["Invoice", `${meta.invoice_number}  ${meta.invoice_date}`], ["Supply", `${inter ? "Inter-state (IGST)" : "Intra-state (CGST + SGST)"} · Prices ${inclusive ? "inclusive" : "exclusive"} of GST`]];
    autoTable(doc, { startY: 30, body: m, theme: "plain", styles: { fontSize: 9 }, columnStyles: { 0: { fontStyle: "bold", cellWidth: 25 } } });
    autoTable(doc, {
      startY: doc.lastAutoTable.finalY + 4,
      head: [["Description", "HSN", "Qty", "Rate", "GST%", "Taxable", "CGST", "SGST", "IGST", "Total"]],
      body: rows.map((r) => [r.description, r.hsn, r.quantity, money(r.unit_price), r.gst_rate, money(r.taxable), money(r.cgst), money(r.sgst), money(r.igst), money(r.total)]),
      foot: [["Total", "", "", "", "", money(tot.taxable), money(tot.cgst), money(tot.sgst), money(tot.igst), money(tot.total)]],
      styles: { fontSize: 8 }, headStyles: { fillColor: [15, 21, 35] }, footStyles: { fillColor: [245, 158, 11], textColor: 20 },
    });
    doc.setFontSize(12);
    doc.text(`Grand total: INR ${money(tot.total)}`, 14, doc.lastAutoTable.finalY + 10);
    doc.save(`gst-${meta.invoice_number || "computation"}.pdf`);
    toast.success("PDF downloaded");
  };

  return (
    <div className="space-y-4">
      <div className="panel p-5 flex flex-wrap items-center gap-3" data-testid="gst-controls">
        <input ref={fileRef} type="file" accept=".pdf,.png,.jpg,.jpeg,.webp" hidden data-testid="gst-file-input" onChange={(e) => extract(e.target.files[0])} />
        <button data-testid="gst-upload-button" disabled={busy} onClick={() => fileRef.current.click()} className="flex items-center gap-2 px-4 py-2 rounded-lg bg-orange-500 hover:bg-orange-400 text-slate-950 text-sm font-semibold transition-colors disabled:opacity-60">
          <Upload size={15} />{busy ? "Reading invoice…" : "Upload invoice (AI extract)"}
        </button>
        <div className="flex rounded-lg border border-slate-800 p-0.5 text-xs">
          {[["Exclusive", false], ["Inclusive", true]].map(([l, v]) => <button key={l} data-testid={`gst-mode-${l.toLowerCase()}`} onClick={() => setInclusive(v)} className={`px-3 py-1.5 rounded-md ${inclusive === v ? "bg-slate-800 text-white" : "text-slate-500"}`}>{l}</button>)}
        </div>
        <div className="flex rounded-lg border border-slate-800 p-0.5 text-xs">
          {[["Intra-state", false], ["Inter-state", true]].map(([l, v]) => <button key={l} data-testid={`gst-supply-${v ? "inter" : "intra"}`} onClick={() => setInter(v)} className={`px-3 py-1.5 rounded-md ${inter === v ? "bg-slate-800 text-white" : "text-slate-500"}`}>{l}</button>)}
        </div>
        <button data-testid="gst-pdf-button" onClick={pdf} className="ml-auto flex items-center gap-2 px-4 py-2 rounded-lg border border-slate-700 hover:border-orange-500/50 text-sm transition-colors"><FileDown size={15} />Download PDF</button>
      </div>
      <div className="panel p-5 grid sm:grid-cols-3 gap-3" data-testid="gst-meta">
        {Object.keys(meta).map((k) => <input key={k} data-testid={`gst-meta-${k}`} className={field} placeholder={k.replace("_", " ")} value={meta[k]} onChange={(e) => setMeta({ ...meta, [k]: e.target.value })} />)}
      </div>
      <div className="panel p-4 flex flex-wrap items-center gap-3" data-testid="gst-save-bar">
        <span className="text-xs font-mono text-slate-500">SAVE TO RETURNS</span>
        <div className="flex rounded-lg border border-slate-800 p-0.5 text-xs">
          {[["Sales (outward)", "sales"], ["Purchase (ITC)", "purchase"]].map(([l, v]) => <button key={v} data-testid={`gst-kind-${v}`} onClick={() => setKind(v)} className={`px-3 py-1.5 rounded-md ${kind === v ? "bg-slate-800 text-white" : "text-slate-500"}`}>{l}</button>)}
        </div>
        <input type="month" data-testid="gst-period-input" value={period} onChange={(e) => setPeriod(e.target.value)} className="bg-slate-950/70 border border-slate-800 rounded-lg px-3 py-1.5 text-sm font-mono outline-none [color-scheme:dark]" />
        <button data-testid="gst-save-invoice-button" onClick={saveInvoice} className="flex items-center gap-2 px-4 py-2 rounded-lg bg-orange-500 hover:bg-orange-400 text-slate-950 text-sm font-semibold transition-colors"><Save size={15} />Save invoice</button>
        {kind === "sales" && !meta.buyer_gstin && <span className="text-[11px] text-slate-500">No buyer GSTIN → counted as B2C</span>}
      </div>
      <div className="panel overflow-x-auto" data-testid="gst-lines-table">
        <table className="w-full text-sm min-w-[820px]">
          <thead className="text-[11px] font-mono text-slate-500 text-left"><tr>{["Description", "HSN/SAC", "Qty", "Unit price", "GST %", "Taxable", inter ? "IGST" : "CGST + SGST", "Total", ""].map((h) => <th key={h} className="px-3 py-3 border-b border-slate-800">{h}</th>)}</tr></thead>
          <tbody>
            {rows.map((r, i) => (
              <tr key={i} className="border-b border-slate-800/60" data-testid={`gst-line-${i}`}>
                <td className="px-2 py-2"><input data-testid={`gst-line-desc-${i}`} className={field} value={r.description} onChange={(e) => upd(i, "description", e.target.value)} /></td>
                <td className="px-2 py-2 w-24"><input data-testid={`gst-line-hsn-${i}`} className={field} value={r.hsn} onChange={(e) => upd(i, "hsn", e.target.value)} /></td>
                <td className="px-2 py-2 w-20"><input data-testid={`gst-line-qty-${i}`} type="number" className={field} value={r.quantity} onChange={(e) => upd(i, "quantity", e.target.value)} /></td>
                <td className="px-2 py-2 w-28"><input data-testid={`gst-line-price-${i}`} type="number" className={field} value={r.unit_price} onChange={(e) => upd(i, "unit_price", e.target.value)} /></td>
                <td className="px-2 py-2 w-24"><select data-testid={`gst-line-rate-${i}`} className={field} value={r.gst_rate} onChange={(e) => upd(i, "gst_rate", e.target.value)}>{[...new Set([...RATES, Number(r.gst_rate)])].map((x) => <option key={x} value={x}>{x}%</option>)}</select></td>
                <td className="px-3 py-2 font-mono text-xs">{money(r.taxable)}</td>
                <td className="px-3 py-2 font-mono text-xs">{inter ? money(r.igst) : `${money(r.cgst)} + ${money(r.sgst)}`}</td>
                <td className="px-3 py-2 font-mono text-xs text-orange-300">{money(r.total)}</td>
                <td className="px-2"><button data-testid={`gst-line-delete-${i}`} onClick={() => setLines(lines.filter((_, j) => j !== i))} className="text-slate-500 hover:text-rose-400"><Trash2 size={14} /></button></td>
              </tr>
            ))}
          </tbody>
        </table>
        <button data-testid="gst-add-line-button" onClick={() => setLines([...lines, newLine()])} className="m-3 flex items-center gap-1.5 text-xs text-orange-400 hover:text-orange-300"><Plus size={14} />Add line</button>
      </div>
      <div className="grid grid-cols-2 md:grid-cols-5 gap-3">
        {[["Taxable value", tot.taxable, "taxable"], ["CGST", tot.cgst, "cgst"], ["SGST", tot.sgst, "sgst"], ["IGST", tot.igst, "igst"], ["Grand total", tot.total, "total"]].map(([l, v, k]) => (
          <div key={k} className={`panel p-4 ${k === "total" ? "border-orange-500/40" : ""}`} data-testid={`gst-total-${k}`}><div className="text-[10px] font-mono uppercase tracking-widest text-slate-500">{l}</div><div className={`font-mono text-lg mt-1 ${k === "total" ? "text-orange-400" : "text-slate-200"}`}>₹{money(v)}</div></div>
        ))}
      </div>
      <button data-testid="gst-ai-explain-button" onClick={() => ask(`Explain this GST computation and flag any issues: ${inter ? "inter-state" : "intra-state"}, prices ${inclusive ? "inclusive" : "exclusive"}. Lines: ${rows.map((r) => `${r.description} HSN ${r.hsn} @${r.gst_rate}% taxable ${money(r.taxable)}`).join("; ")}. Total ₹${money(tot.total)}`, `GST rate HSN ${rows.map((r) => r.hsn || r.description).filter(Boolean).slice(0, 2).join(" ")} India`.replace("HSN  India", "rates India"))}
        className="text-xs text-slate-400 hover:text-orange-400">Ask TaxDesk AI to review this computation →</button>
    </div>
  );
}

export default function TaxDesk({ ask }) {
  const [tab, setTab] = useState("calc");
  return (
    <div className="space-y-4">
      <div className="flex gap-1 p-1 bg-slate-900/70 border border-slate-800 rounded-lg w-fit">
        {[["calc", "Calculator"], ["returns", "Monthly returns"]].map(([v, l]) => (
          <button key={v} data-testid={`taxdesk-tab-${v}`} onClick={() => setTab(v)} className={`px-4 py-1.5 text-xs font-semibold rounded-md transition-colors ${tab === v ? "bg-orange-500 text-slate-950" : "text-slate-400 hover:text-white"}`}>{l}</button>
        ))}
      </div>
      {tab === "calc" ? <Calculator ask={ask} /> : <GstReturns ask={ask} />}
    </div>
  );
}
