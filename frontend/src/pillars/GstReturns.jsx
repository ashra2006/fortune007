import { useCallback, useEffect, useState } from "react";
import { toast } from "sonner";
import { FileDown, Trash2, Sparkles } from "lucide-react";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { api, errMsg } from "@/lib/api";

const money = (n) => Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const HEADS = ["taxable", "cgst", "sgst", "igst"];
const monthLabel = (p) => new Date(`${p}-01T00:00:00`).toLocaleString("en-IN", { month: "long", year: "numeric" });

const Table = ({ testid, head, rows, empty = "No entries" }) => (
  <div className="overflow-x-auto" data-testid={testid}>
    <table className="w-full text-xs">
      <thead className="font-mono text-slate-500 text-left"><tr>{head.map((h) => <th key={h} className="px-3 py-2 border-b border-slate-800 font-normal">{h}</th>)}</tr></thead>
      <tbody>
        {rows.length === 0 ? <tr><td colSpan={head.length} className="px-3 py-4 text-slate-500">{empty}</td></tr> :
          rows.map((r, i) => <tr key={i} className="border-b border-slate-800/50">{r.map((c, j) => <td key={j} className={`px-3 py-2 ${j >= r.length - 5 && typeof c === "string" && /^[\d,.]+$/.test(c) ? "font-mono" : ""}`}>{c}</td>)}</tr>)}
      </tbody>
    </table>
  </div>
);

const Section = ({ title, tag, children }) => (
  <div className="panel p-5 space-y-3">
    <div className="flex items-center gap-2"><span className="text-[10px] font-mono tracking-widest text-orange-400">{tag}</span><h3 className="font-display font-semibold">{title}</h3></div>
    {children}
  </div>
);

const buildPdf = (s) => {
  const doc = new jsPDF();
  const g1 = s.gstr1, g3 = s.gstr3b;
  doc.setFontSize(18); doc.text(`GST Return Summary — ${monthLabel(s.period)}`, 14, 18);
  doc.setFontSize(9); doc.setTextColor(110);
  doc.text(`Generated by Fortune 007 · ${s.counts.sales} sales, ${s.counts.purchases} purchase invoices · For reference only, verify with your CA before filing`, 14, 24);
  doc.setTextColor(20);
  const opts = { styles: { fontSize: 8 }, headStyles: { fillColor: [15, 21, 35] } };
  const title = (t, y) => { doc.setFontSize(12); doc.text(t, 14, y); return y + 3; };
  let y = title("GSTR-3B summary", 34);
  autoTable(doc, { ...opts, startY: y, head: [["Head", "Taxable", "CGST", "SGST", "IGST"]], body: [
    ["3.1 Outward taxable supplies", ...HEADS.map((k) => money(g3.outward[k]))],
    ["4 Eligible ITC (purchases)", ...HEADS.map((k) => money(g3.itc[k]))],
    ["Net tax payable", "", ...["cgst", "sgst", "igst"].map((k) => money(g3.net_payable[k]))],
    ["ITC carried forward", "", ...["cgst", "sgst", "igst"].map((k) => money(g3.itc_carry_forward[k]))],
  ] });
  y = title("GSTR-1 · B2B invoices", doc.lastAutoTable.finalY + 10);
  autoTable(doc, { ...opts, startY: y, head: [["Invoice", "Date", "Buyer", "GSTIN", "Supply", "Taxable", "CGST", "SGST", "IGST", "Total"]],
    body: g1.b2b.map((b) => [b.invoice_number, b.invoice_date, b.buyer_name, b.buyer_gstin, b.supply, ...[...HEADS, "total"].map((k) => money(b[k]))]) });
  y = title(`GSTR-1 · B2C (${g1.b2c_count} invoices)`, doc.lastAutoTable.finalY + 10);
  autoTable(doc, { ...opts, startY: y, head: [["Taxable", "CGST", "SGST", "IGST", "Total"]], body: [[...HEADS, "total"].map((k) => money(g1.b2c[k]))] });
  y = title("GSTR-1 · Rate-wise", doc.lastAutoTable.finalY + 10);
  autoTable(doc, { ...opts, startY: y, head: [["GST %", "Taxable", "CGST", "SGST", "IGST", "Total"]], body: g1.rate_wise.map((r) => [`${r.gst_rate}%`, ...[...HEADS, "total"].map((k) => money(r[k]))]) });
  y = title("GSTR-1 · HSN summary", doc.lastAutoTable.finalY + 10);
  autoTable(doc, { ...opts, startY: y, head: [["HSN/SAC", "Description", "GST %", "Qty", "Taxable", "CGST", "SGST", "IGST", "Total"]],
    body: g1.hsn.map((h) => [h.hsn, h.description, `${h.gst_rate}%`, h.quantity, ...[...HEADS, "total"].map((k) => money(h[k]))]) });
  doc.save(`gst-return-${s.period}.pdf`);
};

export default function GstReturns({ ask }) {
  const [period, setPeriod] = useState(new Date().toISOString().slice(0, 7));
  const [s, setS] = useState(null);
  const [invs, setInvs] = useState([]);

  const load = useCallback(async () => {
    try {
      const [a, b] = await Promise.all([api.get("/gst/summary", { params: { period } }), api.get("/gst/invoices", { params: { period } })]);
      setS(a.data); setInvs(b.data);
    } catch (e) { toast.error(errMsg(e)); }
  }, [period]);
  useEffect(() => { load(); }, [load]);

  const remove = async (id) => { await api.delete(`/gst/invoices/${id}`); load(); };
  if (!s) return <div className="panel h-40 animate-pulse" />;
  const g1 = s.gstr1, g3 = s.gstr3b;

  return (
    <div className="space-y-4" data-testid="gst-returns">
      <div className="panel p-4 flex flex-wrap items-center gap-3">
        <input type="month" data-testid="returns-period-input" value={period} onChange={(e) => e.target.value && setPeriod(e.target.value)} className="bg-slate-950/70 border border-slate-800 rounded-lg px-3 py-1.5 text-sm font-mono outline-none [color-scheme:dark]" />
        <span className="text-sm text-slate-400" data-testid="returns-counts">{s.counts.sales} sales · {s.counts.purchases} purchases</span>
        <button data-testid="returns-ai-button" onClick={() => ask(`Review my GST position for ${monthLabel(period)}. Outward: taxable ₹${money(g3.outward.taxable)}, CGST ${money(g3.outward.cgst)}, SGST ${money(g3.outward.sgst)}, IGST ${money(g3.outward.igst)}. ITC: CGST ${money(g3.itc.cgst)}, SGST ${money(g3.itc.sgst)}, IGST ${money(g3.itc.igst)}. Net payable ₹${money(g3.net_payable.total)}. Note: cross-utilisation of IGST credit applies. Flag issues and filing deadlines.`, `GSTR-3B GSTR-1 due date ${monthLabel(period)}`)}
          className="ml-auto flex items-center gap-1.5 text-xs text-orange-400 hover:text-orange-300"><Sparkles size={13} />Ask AI to review</button>
        <button data-testid="returns-pdf-button" disabled={!invs.length} onClick={() => { buildPdf(s); toast.success("Return summary PDF downloaded"); }}
          className="flex items-center gap-2 px-4 py-2 rounded-lg bg-orange-500 hover:bg-orange-400 text-slate-950 text-sm font-semibold transition-colors disabled:opacity-40"><FileDown size={15} />Download PDF</button>
      </div>

      {invs.length === 0 ? (
        <div className="panel p-10 text-center text-sm text-slate-500" data-testid="returns-empty-state">No invoices saved for {monthLabel(period)}. Use the Calculator tab and click "Save invoice".</div>
      ) : (
        <>
          <div className="grid grid-cols-2 md:grid-cols-4 gap-3" data-testid="returns-3b-cards">
            {[["Output tax", g3.outward.cgst + g3.outward.sgst + g3.outward.igst, "output"], ["Input tax credit", g3.itc.cgst + g3.itc.sgst + g3.itc.igst, "itc"],
              ["Net payable", g3.net_payable.total, "net"], ["Credit carried forward", g3.itc_carry_forward.cgst + g3.itc_carry_forward.sgst + g3.itc_carry_forward.igst, "carry"]].map(([l, v, k]) => (
              <div key={k} className={`panel p-4 ${k === "net" ? "border-orange-500/40" : ""}`} data-testid={`returns-card-${k}`}>
                <div className="text-[10px] font-mono uppercase tracking-widest text-slate-500">{l}</div>
                <div className={`font-mono text-lg mt-1 ${k === "net" ? "text-orange-400" : "text-slate-200"}`}>₹{money(v)}</div>
              </div>
            ))}
          </div>
          <Section title="Summary of tax" tag="GSTR-3B">
            <Table testid="returns-3b-table" head={["Head", "Taxable", "CGST", "SGST", "IGST"]} rows={[
              ["3.1 Outward taxable supplies", ...HEADS.map((k) => money(g3.outward[k]))],
              ["4 Eligible ITC", ...HEADS.map((k) => money(g3.itc[k]))],
              ["Net tax payable", "—", ...["cgst", "sgst", "igst"].map((k) => money(g3.net_payable[k]))],
            ]} />
          </Section>
          <Section title="Outward supplies" tag="GSTR-1">
            <p className="text-xs text-slate-500">B2B invoices</p>
            <Table testid="returns-b2b-table" head={["Invoice", "Date", "Buyer", "GSTIN", "Supply", "Taxable", "CGST", "SGST", "IGST", "Total"]} empty="No B2B sales"
              rows={g1.b2b.map((b) => [b.invoice_number || "—", b.invoice_date || "—", b.buyer_name || "—", b.buyer_gstin, b.supply, ...[...HEADS, "total"].map((k) => money(b[k]))])} />
            <p className="text-xs text-slate-500 pt-2">B2C ({g1.b2c_count} invoices) · Rate-wise · HSN</p>
            <Table testid="returns-b2c-table" head={["B2C taxable", "CGST", "SGST", "IGST", "Total"]} rows={[[...HEADS, "total"].map((k) => money(g1.b2c[k]))]} />
            <Table testid="returns-rate-table" head={["GST %", "Taxable", "CGST", "SGST", "IGST", "Total"]} empty="No sales" rows={g1.rate_wise.map((r) => [`${r.gst_rate}%`, ...[...HEADS, "total"].map((k) => money(r[k]))])} />
            <Table testid="returns-hsn-table" head={["HSN/SAC", "Description", "GST %", "Qty", "Taxable", "CGST", "SGST", "IGST", "Total"]} empty="No sales"
              rows={g1.hsn.map((h) => [h.hsn, h.description, `${h.gst_rate}%`, h.quantity, ...[...HEADS, "total"].map((k) => money(h[k]))])} />
          </Section>
          <Section title="Saved invoices" tag="LEDGER">
            <div className="space-y-1" data-testid="returns-invoice-list">
              {invs.map((i) => (
                <div key={i.id} className="flex items-center gap-3 text-xs py-2 border-b border-slate-800/50 last:border-0" data-testid={`returns-invoice-${i.id}`}>
                  <span className={`px-2 py-0.5 rounded font-mono ${i.kind === "sales" ? "bg-emerald-500/10 text-emerald-400" : "bg-sky-500/10 text-sky-400"}`}>{i.kind === "sales" ? "SALE" : "PURCHASE"}</span>
                  <span className="truncate">{i.meta.invoice_number || "No number"} · {i.kind === "sales" ? i.meta.buyer_name : i.meta.vendor_name}</span>
                  <span className="ml-auto font-mono">₹{money(i.totals.total)}</span>
                  <button data-testid={`returns-invoice-delete-${i.id}`} onClick={() => remove(i.id)} className="text-slate-500 hover:text-rose-400"><Trash2 size={13} /></button>
                </div>
              ))}
            </div>
          </Section>
        </>
      )}
    </div>
  );
}
